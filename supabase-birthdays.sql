-- 생일자: 새 테이블 + RLS + realtime
-- Supabase 대시보드 → SQL Editor에서 이 파일 전체를 실행하세요.
-- 생일은 date. 오늘 생일 여부는 연도를 빼고 월·일만 비교하면 됩니다.

CREATE TABLE IF NOT EXISTS public.birthdays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  birthday date NOT NULL,
  status text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.birthdays ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read birthdays"
ON public.birthdays FOR SELECT
USING (true);

CREATE POLICY "Allow public insert birthdays"
ON public.birthdays FOR INSERT
WITH CHECK (true);

CREATE POLICY "Allow public update birthdays"
ON public.birthdays FOR UPDATE
USING (true);

-- 다른 탭·팀원 브라우저에 실시간 반영
-- 이미 publication에 있으면 "already member of publication" — 무시해도 됩니다.
ALTER PUBLICATION supabase_realtime ADD TABLE public.birthdays;
